const now = new Date().toISOString();

function subject(name: string, color: string, topics: string[]): Subject {
  return {
    id: uid(),
    name,
    color,
    topics: topics.map((t) => ({
      id: uid(),
      name: t,
      status: "pendente" as const,
      updatedAt: now,
    })),
  };
}

